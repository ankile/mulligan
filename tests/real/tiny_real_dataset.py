"""Tiny synthetic real-format LeRobot dataset builder for the trainer tests.

NOT a pytest module (no ``test_`` prefix, so pytest never collects it).

Both trainer harnesses (``tests/real/trainer_harness_dp.py`` and
``tests/real/trainer_harness_iql.py``) build their fixture from
:func:`build_tiny_real_dataset`, so both run over the same bytes.

Design notes
------------
* The schema is the PRODUCTION real-robot schema
  (:func:`mulligan.real.collect.dataset_features.build_real_lerobot_features`) written through
  the PRODUCTION writer (:func:`mulligan.real.collect.dataset_features.save_episode_to_dataset`),
  so every column both real trainers read (``source``, ``success``, ``is_valid``,
  ``reward``, ``done``, ``steps_to_go``, ``intervention``, the ``action.*`` /
  ``observation.state.*`` supplementary columns and the Franka telemetry union)
  exists with production dtypes/semantics. Nothing about the layout is guessed.
* Camera feature names deliberately avoid the station role names
  (``side_1`` / ``wrist_left`` / ...): those trigger
  ``camera_utils.STATION_CAMERA_DEFAULT_CROPS``, whose boxes live in 640x480
  stored-frame pixels and would fall outside a 64x64 fixture frame.
* Content is a pure function of ``seed``: same seed => same pixels, states,
  actions, rewards, outcomes.
"""

from __future__ import annotations

import json
from pathlib import Path

import numpy as np

# Camera feature suffix must match the DP trainer's default --camera-filter
# ("_left") so the suffix path and the explicit --camera-keys path both work.
DEFAULT_CAMERAS: tuple[str, ...] = ("cam_a_left", "cam_b_left")
DEFAULT_FRAME_HW: tuple[int, int] = (64, 64)
DEFAULT_FPS = 15
TASK_NAME = "tiny fixture task"

# Bumped whenever the generated bytes would change, so a stale cached fixture is
# rebuilt instead of silently reused.
_SPEC_VERSION = 1
_SPEC_FILENAME = ".tiny_dataset_spec.json"


def _episode_pixels(
    *,
    ep: int,
    cam_idx: int,
    ep_len: int,
    frame_hw: tuple[int, int],
    rng: np.random.RandomState,
) -> np.ndarray:
    """Deterministic, video-codec-friendly frames of shape (ep_len, H, W, 3) uint8.

    Smooth moving gradients (survive lossy encoding, keep a physical per-channel
    std so ``visual_norm.assert_image_std_physical`` passes) plus a small fixed
    noise field drawn from ``rng`` so the content still depends on the seed.
    """
    h, w = frame_hw
    yy, xx = np.meshgrid(
        np.linspace(0.0, 1.0, h, dtype=np.float64),
        np.linspace(0.0, 1.0, w, dtype=np.float64),
        indexing="ij",
    )
    noise = rng.uniform(-0.05, 0.05, size=(h, w, 3))
    frames = np.empty((ep_len, h, w, 3), dtype=np.uint8)
    for t in range(ep_len):
        phase = (t + 3.0 * ep + 7.0 * cam_idx) / max(ep_len, 1)
        r = 0.5 + 0.45 * np.sin(2 * np.pi * (xx + phase))
        g = 0.5 + 0.45 * np.sin(2 * np.pi * (yy + 0.5 * phase))
        b = 0.5 + 0.45 * np.sin(2 * np.pi * (xx + yy - phase))
        img = np.stack([r, g, b], axis=-1) + noise
        frames[t] = np.clip(img, 0.0, 1.0).astype(np.float64).__mul__(255.0).astype(np.uint8)
    return frames


def _build_episode_data(
    *,
    ep: int,
    ep_len: int,
    cameras: tuple[str, ...],
    frame_hw: tuple[int, int],
    seed: int,
) -> tuple[dict, bool, list[int]]:
    """Build one production-shaped ``episode_data`` dict + its outcome + sources."""
    rng = np.random.RandomState(seed * 1_000_003 + ep)

    # 7D canonical proprio state: cartesian pose (6) + gripper position (1).
    base_pose = rng.uniform(-0.3, 0.3, size=7)
    drift = rng.uniform(-0.02, 0.02, size=7)
    observations = [
        (base_pose + drift * t + 0.01 * rng.standard_normal(7)).astype(np.float32)
        for t in range(ep_len)
    ]
    # 7D canonical action: cartesian velocity (6) + gripper velocity (1).
    actions = [rng.uniform(-0.5, 0.5, size=7).astype(np.float32) for _ in range(ep_len)]

    episode_data: dict = {
        "observations": observations,
        "actions": actions,
        "steps_to_go": [ep_len - 1 - t for t in range(ep_len)],
        "rewards": [0.0] * (ep_len - 1) + [1.0 if ep % 2 == 0 else 0.0],
        "dones": [0] * (ep_len - 1) + [1],
        "joint_positions": [
            rng.uniform(-1.0, 1.0, size=7).astype(np.float32) for _ in range(ep_len)
        ],
        "joint_velocities": [
            rng.uniform(-0.2, 0.2, size=7).astype(np.float32) for _ in range(ep_len)
        ],
        "cartesian_velocities": [
            rng.uniform(-0.2, 0.2, size=6).astype(np.float32) for _ in range(ep_len)
        ],
        "action_info_cartesian_velocity": [a[:6].astype(np.float32) for a in actions],
        "action_info_cartesian_position": [o[:6].astype(np.float32) for o in observations],
        "action_info_joint_velocity": [
            rng.uniform(-0.2, 0.2, size=7).astype(np.float32) for _ in range(ep_len)
        ],
        "action_info_joint_position": [
            rng.uniform(-1.0, 1.0, size=7).astype(np.float32) for _ in range(ep_len)
        ],
        "action_info_gripper_position": [o[6:7].astype(np.float32) for o in observations],
        "action_info_gripper_velocity": [a[6:7].astype(np.float32) for a in actions],
        # Franka telemetry union (always declared by build_real_lerobot_features).
        "franka_motor_torques_external": [
            rng.uniform(-1.0, 1.0, size=7).astype(np.float32) for _ in range(ep_len)
        ],
        "franka_ee_wrench": [
            rng.uniform(-2.0, 2.0, size=6).astype(np.float32) for _ in range(ep_len)
        ],
        "franka_motor_torques_measured": [
            rng.uniform(-1.0, 1.0, size=7).astype(np.float32) for _ in range(ep_len)
        ],
        "franka_joint_torques_computed": [
            rng.uniform(-1.0, 1.0, size=7).astype(np.float32) for _ in range(ep_len)
        ],
    }

    for cam_idx, cam in enumerate(cameras):
        frames = _episode_pixels(ep=ep, cam_idx=cam_idx, ep_len=ep_len, frame_hw=frame_hw, rng=rng)
        episode_data[cam] = [frames[t] for t in range(ep_len)]

    episode_success = ep % 2 == 0
    # DataSource.AUTONOMOUS(0) for the first third, HUMAN(1) afterwards, so the
    # --filter-dagger / IQL source-aware paths see both classes and at least one
    # policy->human intervention boundary.
    n_auto = max(1, ep_len // 3)
    sources = [0] * n_auto + [1] * (ep_len - n_auto)
    return episode_data, episode_success, sources


def _spec_dict(
    *,
    repo_id: str,
    n_episodes: int,
    ep_len: int,
    cameras: tuple[str, ...],
    seed: int,
    frame_hw: tuple[int, int],
    fps: int,
) -> dict:
    return {
        "version": _SPEC_VERSION,
        "repo_id": repo_id,
        "n_episodes": n_episodes,
        "ep_len": ep_len,
        "cameras": list(cameras),
        "seed": seed,
        "frame_hw": list(frame_hw),
        "fps": fps,
    }


def build_tiny_real_dataset(
    root: Path,
    *,
    repo_id: str,
    n_episodes: int = 3,
    ep_len: int = 16,
    cameras: list[str] | tuple[str, ...] = DEFAULT_CAMERAS,
    seed: int = 0,
    frame_hw: tuple[int, int] = DEFAULT_FRAME_HW,
    fps: int = DEFAULT_FPS,
) -> Path:
    """Synthesize a miniature LeRobot v3.0 real-format dataset under ``root/<repo_id>``.

    Returns the dataset directory. Idempotent: an existing directory whose
    ``.tiny_dataset_spec.json`` matches the requested parameters is reused as-is.
    """
    import mulligan

    mulligan.apply_runtime_patches()

    from lerobot.datasets.lerobot_dataset import LeRobotDataset

    from mulligan.real.collect.dataset_features import (
        build_real_lerobot_features,
        save_episode_to_dataset,
    )

    cameras = tuple(cameras)
    frame_hw = tuple(frame_hw)
    root = Path(root)
    ds_dir = root / repo_id
    spec = _spec_dict(
        repo_id=repo_id,
        n_episodes=n_episodes,
        ep_len=ep_len,
        cameras=cameras,
        seed=seed,
        frame_hw=frame_hw,
        fps=fps,
    )
    spec_path = ds_dir / _SPEC_FILENAME
    if spec_path.is_file() and json.loads(spec_path.read_text()) == spec:
        return ds_dir
    if ds_dir.exists():
        import shutil

        shutil.rmtree(ds_dir)

    episodes = [
        _build_episode_data(ep=ep, ep_len=ep_len, cameras=cameras, frame_hw=frame_hw, seed=seed)
        for ep in range(n_episodes)
    ]

    features = build_real_lerobot_features(episodes[0][0], cam_data_keys=list(cameras))
    dataset = LeRobotDataset.create(
        repo_id=repo_id,
        fps=fps,
        features=features,
        root=str(ds_dir),
        robot_type="franka",
    )
    saved = 0
    for episode_data, episode_success, sources in episodes:
        saved = save_episode_to_dataset(
            dataset,
            episode_data,
            episode_success=episode_success,
            camera_keys=list(cameras),
            task_name=TASK_NAME,
            saved_episode_count=saved,
            sources=sources,
            verbose=False,
        )
    dataset.finalize()

    spec_path.write_text(json.dumps(spec, indent=2, sort_keys=True))
    return ds_dir


def camera_feature_keys(cameras: list[str] | tuple[str, ...] = DEFAULT_CAMERAS) -> list[str]:
    """Full LeRobot feature keys for the fixture cameras."""
    return [f"observation.images.{cam}" for cam in cameras]


if __name__ == "__main__":  # pragma: no cover - manual fixture build
    import argparse

    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--root", type=Path, required=True)
    parser.add_argument("--repo-id", type=str, default="tiny/real-tiny")
    parser.add_argument("--n-episodes", type=int, default=3)
    parser.add_argument("--ep-len", type=int, default=16)
    parser.add_argument("--seed", type=int, default=0)
    ns = parser.parse_args()
    print(
        build_tiny_real_dataset(
            ns.root,
            repo_id=ns.repo_id,
            n_episodes=ns.n_episodes,
            ep_len=ns.ep_len,
            seed=ns.seed,
        )
    )
